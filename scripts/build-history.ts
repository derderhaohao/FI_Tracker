// Builds src/domain/history/usHistory.ts from Robert Shiller's monthly data
// (S&P composite, dividends, CPI, 10-year Treasury yield), as republished at
// https://github.com/datasets/s-and-p-500 (data/data.csv).
//
//   npx tsx scripts/build-history.ts path/to/data.csv
//
// Annual figures run January to January, the convention of Shiller's own tables:
// - stocks: (P[Jan y+1] + Σ monthly dividends / 12) / P[Jan y] − 1
// - bonds: a 10-year par bond bought at the January yield, repriced a year later
//   as a 9-year bond at the next January's yield, plus its coupon
// - inflation: CPI[Jan y+1] / CPI[Jan y] − 1
import { readFileSync, writeFileSync } from 'node:fs';

const [, , path] = process.argv;
if (!path) throw new Error('Usage: tsx scripts/build-history.ts data.csv');
const lines = readFileSync(path, 'utf8').trim().split('\n').slice(1);
interface Month {
  price: number;
  dividend: number;
  cpi: number;
  yield10: number;
}
const months = new Map<string, Month>();
for (const line of lines) {
  const [date, price, dividend, , cpi, rate] = line.split(',');
  if (Number(cpi) === 0) continue; // FRED extension rows have price only
  months.set(date.slice(0, 7), {
    price: Number(price),
    dividend: Number(dividend),
    cpi: Number(cpi),
    yield10: Number(rate) / 100,
  });
}

const round = (v: number) => Math.round(v * 1e6) / 1e6;
const rows: { year: number; stocks: number; bonds: number; inflation: number }[] = [];
for (let year = 1871; ; year++) {
  const jan = months.get(`${year}-01`);
  const next = months.get(`${year + 1}-01`);
  if (!jan || !next) break;
  let dividends = 0;
  for (let m = 1; m <= 12; m++)
    dividends += (months.get(`${year}-${String(m).padStart(2, '0')}`)?.dividend ?? 0) / 12;
  const y0 = jan.yield10;
  const y1 = next.yield10;
  const price = (y0 / y1) * (1 - Math.pow(1 + y1, -9)) + Math.pow(1 + y1, -9);
  rows.push({
    year,
    stocks: round((next.price + dividends) / jan.price - 1),
    bonds: round(y0 + price - 1),
    inflation: round(next.cpi / jan.cpi - 1),
  });
}

const body = rows.map((r) => `  [${r.year}, ${r.stocks}, ${r.bonds}, ${r.inflation}],`).join('\n');
writeFileSync(
  new URL('../src/domain/history/usHistory.ts', import.meta.url),
  `// Generated by scripts/build-history.ts from Robert Shiller's data (via datasets/s-and-p-500).
// Do not edit by hand. Columns: year, US stocks total return, 10-year Treasury return, US CPI inflation.
// Each year runs January to January, nominal, as decimals.

export const US_HISTORY_SOURCE =
  'Robert Shiller, Irrational Exuberance data (S&P composite with dividends, 10-year Treasury yield, CPI-U), via github.com/datasets/s-and-p-500';

export const US_HISTORY: readonly (readonly [year: number, stocks: number, bonds: number, inflation: number])[] = [
${body}
];
`,
);
console.log(`Wrote ${rows.length} years: ${rows[0].year}–${rows.at(-1)!.year}`);
